     * [searchValues] with a business-supplied where generator. See [searchMaps] for why the overload
     * exists.
     *
     * @param listSearchPayload List search payload; must carry exactly one `returnProperties` entry
     * @param whereConditionFactory Custom where generator
     * @return The value of that property for each row
     * @author K
     * @author AI: Claude
     * @since 1.0.0
     */
    open fun searchValues(
        listSearchPayload: ListSearchPayload,
        whereConditionFactory: ((Column<Any>, Any?) -> ColumnDeclaring<Boolean>?)? = null
    ): List<Any?> {
        val returnProperties = listSearchPayload.getReturnProperties()
        require(returnProperties != null && returnProperties.size == 1) {
            "searchValues needs exactly one entry in ListSearchPayload.returnProperties to know which " +
                "column's values to return, but got ${returnProperties?.size ?: 0}. Use searchMaps(...) " +
                "for several properties, or search(payload, returnItemClass) for whole objects."
        }
        // A name that is not a property of the entity is silently intersected away upstream, which
        // turns the query into `SELECT *` and the result into one empty map per row — so the caller
        // gets an empty list back from a query that matched plenty of rows. Refusing here is the
        // point of this method existing.
        val property = returnProperties.single()
        require(property in getEntityProperties()) {
            "searchValues was asked for property [$property], which entity " +
                "[${table().entityClass?.simpleName}] does not have. Without this check the query " +
                "would select nothing and hand back an empty list as though no rows matched."
        }
        return searchMaps(listSearchPayload, whereConditionFactory).flatMap { it.values }
    }

