/**
 * Base read-only data access object that encapsulates common query operations for a database table.
 *
 * @param PK Entity primary key type
 * @param E Entity type
 * @param T Type of the database table-entity binding object
 * @author K
 * @author AI: Codex
 * @author AI: Claude
 * @since 1.0.0
 */
open class BaseReadOnlyDao<PK : Any, E : IDbEntity<PK, E>, T : Table<E>> : IBaseReadOnlyDao<PK, E> {

    /** Database table-entity binding object */
    private var table: T? = null

    private var entityClass: KClass<E>? = null

    /**
     * Returns the database table-entity binding object.
     *
     * @return Database table-entity binding object
     * @author K
     * @author AI: Claude
     * @since 1.0.0
     */
    @Suppress("UNCHECKED_CAST")
    protected fun table(): T {
        if (table == null) {
            val tableClass = daoTypeArgument(TABLE_TYPE_ARGUMENT) as KClass<T>
            table = requireNotNull(tableClass.objectInstance) {
                "DAO generic table type [${tableClass.qualifiedName}] must be an object singleton."
            }
        }
        return requireNotNull(table) { "Failed to initialize the table object corresponding to the DAO." }
    }

    /**
     * Returns the entity type corresponding to the current DAO.
     *
     * @return Entity KClass
     */
    @Suppress("UNCHECKED_CAST")
    protected fun entityClass(): KClass<E> {
        if (entityClass == null) {
            entityClass = daoTypeArgument(ENTITY_TYPE_ARGUMENT) as KClass<E>
        }
        return requireNotNull(entityClass) { "Failed to resolve the entity type corresponding to the DAO." }
    }

    /**
     * The concrete class this DAO passes to [BaseReadOnlyDao] as its [index]-th type argument.
     *
     * Walks the whole supertype chain and substitutes type variables on the way up, rather than
     * reading the type arguments off the direct superclass. That distinction is the difference
     * between working and not for two shapes that both show up in practice:
     *
     * - **an intermediate abstract DAO** — the natural way to give a family of tables a shared
     *   method: `abstract class AbstractTenantDao<E : IDbEntity<String, E>, T : Table<E>> :
     *   BaseCrudDao<String, E, T>()`, with `class OrderDao : AbstractTenantDao<Order, Orders>()`
     *   below it. The direct superclass of `OrderDao` parameterises `AbstractTenantDao`, not
     *   `BaseReadOnlyDao`, so its type arguments are in the wrong positions; `E` and `T` are
     *   substituted as the walk passes through.
     * - **a proxied bean** — a CGLIB subclass generated by Spring inserts a level that parameterises
     *   nothing at all.
     *
     * @param index position in `BaseReadOnlyDao<PK, E, T>`
     * @return the concrete class at that position
     * @throws IllegalStateException when the chain does not resolve to a concrete class — a DAO that
     *   is still generic at that position cannot bind to a table, and saying so beats returning the
     *   erased upper bound and failing later with a confusing column error.
     * @author K
     * @author AI: Claude
     * @since 1.0.0
     */
    private fun daoTypeArgument(index: Int): KClass<*> {
        val resolved = resolveDaoTypeArguments(this::class, emptyMap())
            ?: error("Class [${this::class.qualifiedName}] does not extend ${BaseReadOnlyDao::class.simpleName}.")
        val type = resolved.getOrNull(index)
        val classifier = type?.classifier
        return classifier as? KClass<*> ?: error(
            "Cannot resolve type argument #$index of ${BaseReadOnlyDao::class.simpleName} for DAO " +
                "[${this::class.qualifiedName}]; it resolved to [${type ?: "nothing"}]. A DAO must fix " +
                "all three type arguments (primary key, entity, table) to a concrete type."
        )
    }

    companion object {
        private val log = LogFactory.getLog(BaseReadOnlyDao::class)

        /** Positions in `BaseReadOnlyDao<PK, E, T>`. */
        private const val ENTITY_TYPE_ARGUMENT = 1
        private const val TABLE_TYPE_ARGUMENT = 2

        /** The three meta properties the ktorm `Entity` interface adds, which are not business fields. */
        private val ENTITY_META_PROPERTIES = setOf("entityClass", "properties", "changedProperties")

        /**
         * Property names per class, memoised.
         *
         * A class's property list cannot change at runtime, and every payload query reflects at
         * least twice — once for the table entity and once for the return type — so recomputing it
         * is pure waste on the framework's hottest path. Keyed by [KClass], which is itself
         * canonical per class, so the map is bounded by the number of entity and VO types a
         * deployment actually queries.
         */
        private val propertyNameCache = ConcurrentHashMap<KClass<*>, List<String>>()

        private val businessPropertyNameCache = ConcurrentHashMap<KClass<*>, List<String>>()

        /** All property names declared on [klass]. */
        private fun propertyNamesOf(klass: KClass<*>): List<String> =
            propertyNameCache.getOrPut(klass) { klass.memberProperties.map { it.name } }

        /** Property names of [klass] minus the ktorm `Entity` meta properties. */
        private fun businessPropertyNamesOf(klass: KClass<*>): List<String> =
            businessPropertyNameCache.getOrPut(klass) {
                propertyNamesOf(klass).filter { it !in ENTITY_META_PROPERTIES }
            }

        /**
         * Depth-first search up [klass]'s supertypes for [BaseReadOnlyDao], carrying [substitutions]
         * — that class's own type parameter names bound to the concrete types the level below
         * supplied for them.
         *
         * @return the type arguments [BaseReadOnlyDao] ends up parameterised with, or null when this
         *   branch of the hierarchy does not reach it
         */
        private fun resolveDaoTypeArguments(
            klass: KClass<*>,
            substitutions: Map<String, KType>,
        ): List<KType?>? {
            for (superType in klass.supertypes) {
                val superClass = superType.classifier as? KClass<*> ?: continue
                if (superClass != BaseReadOnlyDao::class && !superClass.isSubclassOf(BaseReadOnlyDao::class)) {
                    continue
                }
                // The supertype's arguments are written in terms of `klass`'s type parameters, so
                // they are resolved against the substitutions gathered on the way here.
                val arguments = superType.arguments.map { argument ->
                    val type = argument.type
                    when (val classifier = type?.classifier) {
                        is KTypeParameter -> substitutions[classifier.name]
                        else -> type
                    }
                }
                if (superClass == BaseReadOnlyDao::class) return arguments
                val next = superClass.typeParameters.map { it.name }.zip(arguments)
                    .mapNotNull { (name, type) -> type?.let { name to it } }
                    .toMap()
                resolveDaoTypeArguments(superClass, next)?.let { return it }
            }
            return null
        }
    }

    /**
     * Returns the set of sortable property names based on [io.kudos.base.query.sort.Sortable] annotations
     * on the entity (PO) bound to the current DAO's table (independent of the VO/PO return type in the request).
     */
    protected fun sortWhitelistFromPo(): Set<String> {
        val ec = table().entityClass ?: return emptySet()
        return sortablePropertyNamesForEntity(ec)
    }

    /**
     * Filters client-supplied sort orders by the [io.kudos.base.query.sort.Sortable] annotations on the PO.
     * Every property used for sorting must have the corresponding annotation on the PO; unannotated entries
     * are logged at WARN (with entity class and property name) and ignored in the query.
     * [whitelist] contains all @Sortable property names on the PO; if the PO has no @Sortable annotations,
     * [whitelist] is empty and all requested sort entries are ignored with a warning.
     */
    protected fun filterOrdersBySortWhitelist(rawOrders: List<Order>?, whitelist: Set<String>): List<Order> {
        val list = rawOrders ?: emptyList()
        val rejected = list.filter { it.property !in whitelist }
        if (rejected.isNotEmpty()) {
            val entityName = table().entityClass?.qualifiedName
                ?: table().entityClass?.simpleName
                ?: "unknown"
            for (order in rejected) {
                log.warn(
                    "Sort property in query request is not annotated with @Sortable on the table entity; ignored: entityClass={0}, property={1}",
                    entityName,
                    order.property
                )
            }
        }
        return list.filter { it.property in whitelist }
    }

